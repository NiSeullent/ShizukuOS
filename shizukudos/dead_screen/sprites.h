#ifndef SHZ_DEAD_SCREEN_SPRITES_H
#define SHZ_DEAD_SCREEN_SPRITES_H
#include <stdint.h>
/* Original 16x16 1bpp item sprites (not copied OS assets). Static const rodata:
 * no allocation, no init; bit 15 is the left column. Level 0 Sad Mac, 1..5 =
 * Win2000, XP, 8.1, 10, 11 BSOD. Safe to read in the panic context. */
#define DS_SPRITE_SIZE 16u
#define DS_SPRITE_COUNT 6u
static const uint16_t ds_sprites[DS_SPRITE_COUNT][DS_SPRITE_SIZE] = {
 {0x0000,0x3ffc,0x2004,0x2c34,0x2a54,0x2994,0x2954,0x2a34,0x2004,0x23c4,0x2424,0x2004,0x3ffc,0x2004,0x27e4,0x3ffc}, /* Sad Mac */
 {0xffff,0x8001,0xbdef,0x8001,0xbffd,0x8001,0xbf7d,0x8001,0xb7fd,0x8001,0xbf6d,0x8001,0xbdbd,0x8001,0x8001,0xffff}, /* 2000 */
 {0xffff,0x8001,0x9ffd,0x8001,0xb7ef,0x8001,0xbffd,0x8001,0xbdf7,0x8001,0xbf7d,0x8001,0xb6ff,0x8001,0x8001,0xffff}, /* XP */
 {0xffff,0x8001,0x8c01,0x9201,0x8201,0x8401,0x8001,0xbfe1,0x8001,0xbff1,0x8001,0xbe01,0x8001,0x8001,0x8001,0xffff}, /* 8.1 */
 {0xffff,0x8001,0x8b01,0x9101,0x8d01,0x8001,0xbfc1,0x8001,0xbfe1,0x8001,0x8781,0x8781,0x8661,0x8661,0x8001,0xffff}, /* 10 */
 {0xffff,0xc003,0xa005,0x9189,0x8d11,0x8001,0x9fe1,0x8001,0x9ff1,0x8001,0x9781,0x9781,0x9661,0x9661,0xa005,0xffff}  /* 11 */
};
static inline unsigned ds_sprite_bit(unsigned level, unsigned x, unsigned y)
{
    if(level>=DS_SPRITE_COUNT || x>=DS_SPRITE_SIZE || y>=DS_SPRITE_SIZE) return 0;
    return (ds_sprites[level][y]>>(15u-x))&1u;
}
#endif
