W64 = SHZ / "win64"
OUT = BUILD / "win64"
CC = "x86_64-w64-mingw32-gcc"
DLLTOOL = "x86_64-w64-mingw32-dlltool"
WINDRES = "x86_64-w64-mingw32-windres"
NTSYS = SHZ / "kernel64" / "ntsys.h"

COMMON = ["-O2", "-Wall", "-Wextra", "-Werror", "-ffreestanding", "-fno-builtin", "-fno-stack-protector",
          "-mno-red-zone", "-fno-ident", "-fno-tree-loop-distribute-patterns",
          "-Wno-unused-function", "-Wno-unused-parameter", "-Wno-cast-function-type"]
NTDLL_BASE = "0x7ffb00000000"
K32_BASE = "0x7ffb10000000"
RES = OUT / "res"                       # generated version resources (tools/verres.py)


def version_obj(filename, description, filetype=verres.VFT_DLL, fmt="coff", extra_rc=None):
    """The compiled VS_VERSIONINFO of one image (every DLL and EXE gets one; see tools/verres.py)."""
    return verres.compile_version(RES, filename, description, filetype, fmt=fmt, extra_rc=extra_rc)


def syscall_list():
    text = NTSYS.read_text()
    block = text[text.index("#define SYSCALL_LIST(X)"):text.index("enum {")]
    return [(m.group(1), int(m.group(2), 16)) for m in re.finditer(r"X\((\w+), (0x[0-9a-fA-F]+)\)", block)]


def gen_stubs():
    """One `mov r10, rcx; mov eax, N; syscall; ret` stub per system call (Windows x64 convention)."""
    lines = ["# Generated by shizukudos/win64/build.py from kernel64/ntsys.h. Do not edit.", "    .text"]
    exports = []
    for name, num in syscall_list():
        lines += [f"    .globl {name}", f"    .def {name}; .scl 2; .type 32; .endef", f"{name}:",
                  "    movq %rcx, %r10", f"    movl ${num}, %eax", "    syscall", "    ret"]
        exports.append(name)
        exports.append(f"Zw{name[2:]} = {name}")
    (OUT / "nt_stubs.S").write_text("\n".join(lines) + "\n")
    return exports


EXPORT_PATTERNS = {
    # SHZ_EXPORT <type> NTAPI Name(   (the SHZ_EXPORT prefix is optional; NTAPI/__cdecl names the calling convention)
    "NTAPI": r"^(?:SHZ_EXPORT\s+)?[A-Za-z_][\w\s\*]*?\b(?:NTAPI|__cdecl)\s+\**(\w+)\s*\(",
    # K32API <type> WINAPI Name(      (the name is the last identifier before the parameter list)
    "K32API": r"^K32API\s[^;{()]*?\b(\w+)\s*\(",
    # DLLAPI <type> WINAPI Name(      (extra modules under win64/dlls/<name>/)
    "DLLAPI": r"^DLLAPI\s[^;{()]*?\b(\w+)\s*\(",
}


def scan_exports(paths, marker):
    names = []
    for path in paths:
        text = path.read_text()
        names += [m.group(1) for m in re.finditer(EXPORT_PATTERNS[marker], text, re.M)]
    return sorted(set(names))


def write_def(path, library, names, forwarders=(), ordinals=None):
    """ordinals: {name: ordinal} to pin (module.json "ordinals"): the Windows ordinals programs import by number (the
    Winsock 1.1 exports of ws2_32, for instance); every other export gets whatever ordinal the linker assigns."""
    ordinals = ordinals or {}
    missing = sorted(set(ordinals) - set(names))
    if missing:
        raise SystemExit(f"{library}: pinned ordinals for names that are not exported: {missing}")
    body = [f"LIBRARY {library}", "EXPORTS"]
    body += [f"  {n} @{ordinals[n]}" if n in ordinals else f"  {n}" for n in names]
    body += [f"  {f}" for f in forwarders]
    path.write_text("\n".join(body) + "\n")


def version_resource(rc):
    """Compiles a DLL's VERSIONINFO script (windres) and returns the object to link; programs read a system DLL's file
    version to learn the Windows build (Chromium base::win::OSInfo::Kernel32Version, crashpad's module list)."""
    res = OUT / (rc.stem + "_res.o")
    run([WINDRES, "-O", "coff", "-o", res, rc])
    return res


def build_ntdll():
    src = sorted((W64 / "ntdll").glob("*.c"))
    stub_exports = gen_stubs()
    names = scan_exports(src, "NTAPI")
    names = [n for n in names if n not in ("ShzInitSync",)]
    entries = names + ["RtlCaptureContext", "__C_specific_handler"] + stub_exports
    ordinal_file = W64 / "ntdll" / "ordinals.json"
    if ordinal_file.exists():
        policy = json.loads(ordinal_file.read_text())
        pins = policy.get("ordinals", {})
        actual_names = {entry.split("=", 1)[0].strip() for entry in entries}
        if (policy.get("library") != "ntdll.dll" or not isinstance(pins, dict) or set(pins) != actual_names
                or any(type(value) is not int or not 1 <= value <= 65535 for value in pins.values())
                or len(set(pins.values())) != len(pins)):
            raise SystemExit("ntdll.dll: exact named-export ordinal coverage and unique valid ordinals required")
        definitions = sorted({entry for entry in entries if "=" not in entry})
        aliases = sorted({entry for entry in entries if "=" in entry})
        for alias in aliases:
            name, target = (part.strip() for part in alias.split("=", 1))
            if target not in definitions:
                raise SystemExit(f"ntdll.dll: alias {name} has no actual local target {target}")
        alias_entries = [f"{entry} @{pins[entry.split('=', 1)[0].strip()]}" for entry in aliases]
        write_def(OUT / "ntdll.def", "ntdll.dll", definitions, alias_entries,
                  {name: pins[name] for name in definitions})
    else:
        write_def(OUT / "ntdll.def", "ntdll.dll", entries)
    dll = OUT / "ntdll.dll"
    cmd = [CC, *COMMON, "-DSHZ_NTDLL_BUILD", "-shared", "-nostdlib", "-Wl,--entry,ShzNtdllEntry",
           f"-Wl,--image-base,{NTDLL_BASE}", "-Wl,--dynamicbase", "-Wl,--subsystem,console", "-Wl,--kill-at",
           "-I", W64 / "include", *src, W64 / "ntdll" / "ntdll_asm.S", OUT / "nt_stubs.S", OUT / "ntdll.def",
           version_obj("ntdll.dll", "NT Layer DLL"), "-lgcc", "-o", dll]
    run(cmd)
    run([DLLTOOL, "-d", OUT / "ntdll.def", "-l", OUT / "libntdll.a", "--kill-at"])
    return dll, cmd, names


def build_kernel32(ntdll_names):
    src = sorted((W64 / "kernel32").glob("*.c"))
    names = scan_exports(src, "K32API")
    forwards = [f"{n} = ntdll.{n}" for n in ("RtlCaptureContext", "RtlLookupFunctionEntry", "RtlVirtualUnwind", "RtlUnwindEx",
                                                 "RtlUnwind", "RtlPcToFileHeader", "RtlRaiseException", "RtlCaptureStackBackTrace",
                                                 "VerSetConditionMask")
                if n in ntdll_names or n == "RtlCaptureContext"]
    names = [n for n in names if n not in ("RtlUnwindKernel32",)]
    # Windows kernel32 forwards these to ntdll too (V8 and Chromium import them from kernel32); delay-load resolution is
    # the api-ms-win-core-delayload contract, hosted by kernel32 here (kernelbase on Windows).
    forwards += [f"{n} = ntdll.{t}" for n, t in (
        ("RtlAddFunctionTable", "RtlAddFunctionTable"), ("RtlDeleteFunctionTable", "RtlDeleteFunctionTable"),
        ("RtlInstallFunctionTableCallback", "RtlInstallFunctionTableCallback"), ("RtlRestoreContext", "RtlRestoreContext"),
        ("ResolveDelayLoadedAPI", "LdrResolveDelayLoadedAPI"), ("ResolveDelayLoadsFromDll", "LdrResolveDelayLoadsFromDll"))
        if t in ntdll_names]
    write_def(OUT / "kernel32.def", "kernel32.dll", names, forwards)
    dll = OUT / "kernel32.dll"
    cmd = [CC, *COMMON, "-shared", "-nostdlib", "-Wl,--entry,ShzKernel32Entry", f"-Wl,--image-base,{K32_BASE}",
           "-Wl,--dynamicbase", "-Wl,--subsystem,console", "-Wl,--kill-at", "-I", W64 / "include", *src,
           OUT / "kernel32.def", version_obj("kernel32.dll", "Windows NT BASE API Client DLL"), "-L", OUT, "-lntdll", "-lgcc", "-o", dll]
    run(cmd)
    run([DLLTOOL, "-d", OUT / "kernel32.def", "-l", OUT / "libkernel32.a", "--kill-at"])
    return dll, cmd, names


DLL_BASE = 0x7ffb20000000
DLL_STRIDE = 0x01000000


def discover_modules():
    """Extra system DLLs: every win64/dlls/<name>/ containing *.c builds <name>.dll (+ lib<name>.a) and is packed as
    \\SHZ\\SYS64\\<name>.dll. Exported functions are the DLLAPI-marked definitions. Optional module.json:
    {"libs": ["advapi32"], "forwarders": ["Name = other.Name"], "description": "..."} lists other modules this one imports
    from; "description" is the FileDescription of its version resource (default: "<name>.dll")."""
    root = W64 / "dlls"
    found = []
    for d in sorted(root.glob("*")) if root.is_dir() else []:
        if d.is_dir() and sorted(d.glob("*.c")):
            cfg = json.loads((d / "module.json").read_text()) if (d / "module.json").exists() else {}
            found.append((d.name, d, cfg))
    return found


def build_modules():
    pending = {name: (d, cfg) for name, d, cfg in discover_modules()}
    built, order = {}, []
    while pending:
        ready = [n for n, (d, cfg) in sorted(pending.items()) if all(l in built for l in cfg.get("libs", []) if l in pending or l in built)]
        if not ready:
            raise SystemExit(f"circular or missing module dependency among {sorted(pending)}")
        for name in ready:
            d, cfg = pending.pop(name)
            src = sorted(d.glob("*.c"))
            names = scan_exports(src, "DLLAPI")
            write_def(OUT / f"{name}.def", f"{name}.dll", names, cfg.get("forwarders", []), cfg.get("ordinals"))
            has_main = any(re.search(r"\bDllMain\s*\(", s.read_text()) for s in src)
            base = DLL_BASE + DLL_STRIDE * len(order)
            dll = OUT / f"{name}.dll"
            cmd = [CC, *COMMON, "-DBUILDING_" + name.upper(), "-shared", "-nostdlib", f"-Wl,--entry,{'DllMain' if has_main else '0'}",
                   f"-Wl,--image-base,{base:#x}", "-Wl,--dynamicbase", "-Wl,--subsystem,console", "-Wl,--kill-at",
                   "-I", W64 / "include", "-I", d, *src, OUT / f"{name}.def",
                   version_obj(f"{name}.dll", cfg.get("description", f"{name}.dll")), "-L", OUT,
                   *[f"-l{l}" for l in ["kernel32", "ntdll", *cfg.get("libs", [])]], "-lgcc", "-o", dll]
            run(cmd)
            run([DLLTOOL, "-d", OUT / f"{name}.def", "-l", OUT / f"lib{name}.a", "--kill-at"])
            run([DLLTOOL, "-d", OUT / f"{name}.def", "-y", OUT / f"lib{name}_delay.a", "--kill-at"])  # delay-import lib
            built[name] = {"dll": dll, "cmd": cmd, "exports": names, "base": base}
            order.append(name)
    return built


# The runners check that T_HELLO.EXE sees its preferred base 0x140000000, so it is linked without DYNAMIC_BASE (a fixed
# image); T_LAZY.EXE is fixed at 0x140000000 too, so D:\LAZY\BIGRELOC.DLL (same preferred base) must be relocated.
# Every other app is relocatable and receives an ASLR base from the Kernel64 loader.
FIXED_BASE_APPS = {"t_hello", "t_lazy"}

# Apps that link a module through its DELAY-import library instead of its ordinary import library: the functions are
# resolved lazily on first call (dlltool --output-delaylib + crt/shzcrt.c __delayLoadHelper2 -> ResolveDelayLoadedAPI).
DELAY_MODULES = {"t_delay": ("winmm", "version")}


def build_apps(module_libs=()):
    apps = {}
    for src in sorted((W64 / "tests").glob("t_*.c")):
        name = src.stem
        exe = OUT / f"{name}.exe"
        rc = src.with_suffix(".rc")                       # optional resource script (e.g. a VERSIONINFO fixture)
        extra = [version_obj(f"{name}.exe", f"Shizuku Win64 self-check {name}", verres.VFT_APP, extra_rc=rc if rc.exists() else None)]
        crt = W64 / "crt"
        delayed = DELAY_MODULES.get(name, ())
        libs = [(f"{l}_delay" if l in delayed else l) for l in module_libs]
        cmd = [CC, *COMMON, "-nostdlib", "-Wl,--entry,ShzStart", "-Wl,--subsystem,console", "-Wl,--kill-at",
               "-Wl,--image-base,0x140000000", *(["-Wl,--disable-dynamicbase"] if name in FIXED_BASE_APPS else []),
               "-I", W64 / "include", "-I", crt, src, crt / "shzcrt.c", *extra,
               "-L", OUT, *[f"-l{l}" for l in libs], "-lkernel32", "-lntdll", "-lgcc", "-o", exe]
        run(cmd)
        apps[name] = (exe, cmd)
    return apps


