"""Build the WebKit port's third-party dependencies for the Kernel64 Win64 runtime (agent W3).

Toolchain: the shared WebKit toolchain (deps/toolchain.py: clang 18 for x86_64-w64-mingw32, a mingw-w64 v13 UCRT
sysroot, libc++ 18 as DLLs, the CRT shim and the Win32 compat library that its clang wrappers link first), through
agent W1's CMake toolchain file (webkit/toolchain-mingw-clang.cmake). ICU is W1's static ICU (webkit/build.py
build_icu), shared with JavaScriptCore. Every other dependency is a pinned upstream in shizukudos/upstream/manifest.json
(fetched shallowly into build/upstream, never committed; local changes are patches under deps/patches/<name>/), built
as a static library into one prefix, so each WebKit image carries one copy of everything but the C++ runtime DLLs:

  build/shizukudos/win64/webkit/deps/{include,lib}   headers, static libraries, pkg-config and CMake files
  build/shizukudos/win64/webkit/deps/deps.json       per dependency: pin, licence, libraries (bytes, sha256), seconds

Guest checks: deps/tests/t_*.c(pp), built by --tests, run by deps/run_deps_guest.py.

Usage: build_deps.py [--only NAME[,NAME]] [--tests] [--clean]
"""
