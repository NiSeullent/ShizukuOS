def prepare():
    """The shared toolchain (built if missing), W1's static ICU (cached by W1's stamp) and library aliases."""
    global ICU_PREFIX
    w1.ensure_toolchain()
    w1.OUT.mkdir(parents=True, exist_ok=True)
    WORK.mkdir(parents=True, exist_ok=True)
    ICU_PREFIX = w1.build_icu(w1.ensure_tree("icu"), {})
    w1.lib_aliases()
    PREFIX.mkdir(parents=True, exist_ok=True)


def record(upstream, seconds, before):
    spec = shzlib.load_manifest()["upstreams"][upstream]
    libs = sorted(set((PREFIX / "lib").glob("*.a")) - before)
    return {"upstream": upstream, "ref": spec["ref"], "commit": spec["commit"], "license": spec["license"],
            "build_seconds": round(seconds, 1),
            "libs": {p.name: {"bytes": p.stat().st_size, "sha256": shzlib.sha256_file(p)} for p in libs}}


def build(only=None, clean=False):
    if clean and PREFIX.exists():
        shutil.rmtree(PREFIX)
    prepare()
    state_file = PREFIX / "deps.json"
    state = json.loads(state_file.read_text()) if state_file.exists() else {}
    state["toolchain"] = json.loads((TC / "toolchain.json").read_text())
    state["icu"] = {"prefix": str(ICU_PREFIX), "commit": w1.spec("icu")["commit"],
                    "libs": {p.name: p.stat().st_size for p in sorted((ICU_PREFIX / "lib").glob("*.a"))}}
    for name, (fn, upstream) in DEPS.items():
        if only and name not in only:
            continue
        print(f"== {name}", flush=True)
        before = set((PREFIX / "lib").glob("*.a")) if (PREFIX / "lib").exists() else set()
        for old in state.get(name, {}).get("libs", {}):
            before.discard(PREFIX / "lib" / old)
        t0 = time.time()
        fn(patched_source(upstream))
        state[name] = record(upstream, time.time() - t0, before)
        state_file.write_text(json.dumps(state, indent=1) + "\n")
    return state


def build_tests(only=None):
    """deps/tests/t_*.c(pp) -> build/shizukudos/win64/webkit/deps-tests/*.exe (static dependencies; linked by clang++
    because static ICU/HarfBuzz/woff2 need the C++ runtime)."""
    if ICU_PREFIX is None:
        prepare()
    TOUT.mkdir(parents=True, exist_ok=True)
    spec = json.loads((TESTS / "tests.json").read_text())
    out = {}
    for src in sorted(TESTS.glob("t_*.c*")):
        name = src.stem
        if only and name not in only:
            continue
        t = spec.get(name, {})
        drv = CXX if src.suffix == ".cpp" else CC
        std = ["-std=c++20"] if src.suffix == ".cpp" else ["-std=c11"]
        exe, obj = TOUT / f"{name}.exe", TOUT / f"{name}.o"
        run([*drv, "-O2", "-Wall", "-Wextra", "-Werror", *std, *t.get("defines", []),
             "-I", PREFIX / "include", "-I", ICU_PREFIX / "include",
             *[f"-I{PREFIX / 'include' / d}" for d in t.get("include_dirs", [])], "-c", src, "-o", obj],
            env=env(), timeout=600)
        run([*CXX, obj, "-L", PREFIX / "lib", "-L", ICU_PREFIX / "lib", *[f"-l{l}" for l in t.get("libs", [])],
             "-o", exe], env=env(), timeout=600)
        out[name] = exe
    return out


def runtime_dlls():
    return [SYSROOT / "bin" / d for d in w1.RUNTIME_DLLS]


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--only", help="comma-separated dependency names")
    ap.add_argument("--tests", action="store_true", help="only build the guest checks (deps/tests)")
    ap.add_argument("--clean", action="store_true")
    a = ap.parse_args()
    only = set(a.only.split(",")) if a.only else None
    if a.tests:
        print(json.dumps({k: str(v) for k, v in build_tests(only).items()}, indent=1))
    else:
        print(json.dumps(build(only, a.clean), indent=1))
