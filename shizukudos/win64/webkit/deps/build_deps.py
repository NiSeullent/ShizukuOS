# ------------------------------------------------------------------------------------------------ fetching
def fetch(name):
    """Shallow (optionally sparse) fetch of a manifest-pinned upstream into build/upstream/<name>; verifies the pin."""
    spec = shzlib.load_manifest()["upstreams"][name]
    dest = REPO / "build" / "upstream" / name
    head = lambda: subprocess.run(["git", "-C", str(dest), "rev-parse", "HEAD"], capture_output=True,  # noqa: E731
                                  text=True).stdout.strip()
    if (dest / ".git").exists() and head() == spec["commit"]:
        return dest
    if dest.exists():
        shutil.rmtree(dest)
    dest.mkdir(parents=True)
    run(["git", "-C", dest, "init", "-q"])
    run(["git", "-C", dest, "remote", "add", "origin", spec["repository"]])
    if spec.get("sparse_paths"):
        run(["git", "-C", dest, "sparse-checkout", "set", "--no-cone", *spec["sparse_paths"]])
    run(["git", "-C", dest, "fetch", "-q", "--depth", "1", "origin", spec["commit"]], timeout=3600)
    run(["git", "-C", dest, "checkout", "-q", "FETCH_HEAD"], timeout=1800)
    if head() != spec["commit"]:
        raise RuntimeError(f"{name}: pinned {spec['commit']} but found {head()}")
    return dest


def patched_source(name):
    """Pristine copy of the pinned tree (without .git) with deps/patches/<name>/*.patch applied in order."""
    src = fetch(name)
    dest = WORK / f"src-{name}"
    if dest.exists():
        shutil.rmtree(dest)
    shutil.copytree(src, dest, symlinks=True, ignore=shutil.ignore_patterns(".git"))
    for patch in sorted((HERE / "patches" / name).glob("*.patch")):
        run(["patch", "-p1", "-N", "--quiet", "-d", dest, "-i", patch])
    return dest


def env():
    e = dict(os.environ)
    e["PKG_CONFIG_LIBDIR"] = str(PREFIX / "lib" / "pkgconfig")
    e["PKG_CONFIG_PATH"] = ""
    e.update(toolchain_env())
    return e


def toolchain_env():
    return {"SHZ_WEBKIT_TOOLCHAIN": str(TC / "toolchain.cmake"), "SHZ_ICU_PREFIX": str(ICU_PREFIX),
            "SHZ_LIBALIAS": str(w1.OUT / "libalias")}


# ------------------------------------------------------------------------------------------------ build systems
def toolchain_file():
    """W1's CMake toolchain file, extended (not forked) with this prefix on the find path."""
    f = WORK / "toolchain-deps.cmake"
    f.write_text(f"""# generated by shizukudos/win64/webkit/deps/build_deps.py
include({WEBKIT / 'toolchain-mingw-clang.cmake'})
list(APPEND CMAKE_FIND_ROOT_PATH {PREFIX})
""")
    return f


def cmake_build(name, src, defs):
    b = WORK / f"build-{name}"
    if b.exists():
        shutil.rmtree(b)
    base = {"CMAKE_TOOLCHAIN_FILE": toolchain_file(), **toolchain_env(), "CMAKE_BUILD_TYPE": "Release",
            "CMAKE_INSTALL_PREFIX": PREFIX, "CMAKE_PREFIX_PATH": PREFIX, "BUILD_SHARED_LIBS": "OFF",
            "CMAKE_INSTALL_LIBDIR": "lib", "CMAKE_INSTALL_BINDIR": "bin"}
    base.update(defs)
    run(["cmake", "-G", "Ninja", "-S", src, "-B", b, "-Wno-dev", *[f"-D{k}={v}" for k, v in base.items()]],
        env=env(), timeout=1800)
    run(["ninja", "-C", b, "-j", JOBS], env=env(), timeout=14400)
    run(["ninja", "-C", b, "install"], env=env(), timeout=1800)


def meson_build(name, src, opts):
    b = WORK / f"build-{name}"
    if b.exists():
        shutil.rmtree(b)
    cross = WORK / "meson-cross.txt"
    cross.write_text(f"""[binaries]
c = '{CC[0]}'
cpp = '{CXX[0]}'
c_ld = 'lld'
cpp_ld = 'lld'
ar = '{shutil.which("llvm-ar")}'
strip = '{shutil.which("llvm-strip")}'
windres = '{shutil.which("x86_64-w64-mingw32-windres")}'
pkg-config = '{shutil.which("pkg-config")}'

[properties]
pkg_config_libdir = '{PREFIX}/lib/pkgconfig'

[host_machine]
system = 'windows'
cpu_family = 'x86_64'
cpu = 'x86_64'
endian = 'little'
""")
    run(["meson", "setup", b, src, "--cross-file", cross, f"--prefix={PREFIX}", "--libdir=lib",
         "--buildtype=release", "-Ddefault_library=static", *[f"-D{k}={v}" for k, v in opts.items()]],
        env=env(), timeout=1800)
    run(["ninja", "-C", b, "-j", JOBS], env=env(), timeout=14400)
    run(["ninja", "-C", b, "install"], env=env(), timeout=1800)


# ------------------------------------------------------------------------------------------------ the dependencies
ZLIB = lambda: {"ZLIB_LIBRARY": PREFIX / "lib" / "libz.a", "ZLIB_INCLUDE_DIR": PREFIX / "include"}  # noqa: E731


def b_zlib(src):
    cmake_build("zlib", src, {"ZLIB_BUILD_EXAMPLES": "OFF", "INSTALL_PKGCONFIG_DIR": PREFIX / "lib" / "pkgconfig"})
    lib = PREFIX / "lib"
    shutil.copyfile(lib / "libzlibstatic.a", lib / "libz.a")         # the name FindZLIB and zlib.pc (-lz) use
    (lib / "libzlib.dll.a").unlink(missing_ok=True)                   # zlib 1.3.1 builds its DLL regardless
    for dll in (PREFIX / "bin").glob("libzlib*.dll"):
        dll.unlink()


