def icu_pkgconfig():
    """pkg-config files for W1's static ICU (its install step does not write them): icu-uc, icu-i18n."""
    pc = PREFIX / "lib" / "pkgconfig"
    pc.mkdir(parents=True, exist_ok=True)
    version = w1.spec("icu")["ref"].replace("release-", "").replace("-", ".")
    for name, libs in (("icu-uc", "-licuuc -licudt"), ("icu-i18n", "-licuin")):
        req = "" if name == "icu-uc" else "Requires: icu-uc\n"
        (pc / f"{name}.pc").write_text(
            f"prefix={ICU_PREFIX}\nlibdir=${{prefix}}/lib\nincludedir=${{prefix}}/include\n\nName: {name}\n"
            f"Description: ICU (W1's static build)\nVersion: {version}\n{req}Libs: -L${{libdir}} {libs}\n"
            f"Cflags: -I${{includedir}} -DU_STATIC_IMPLEMENTATION\n")


