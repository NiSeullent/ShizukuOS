def b_sqlite(src):
    host = WORK / "build-sqlite-host"
    if host.exists():
        shutil.rmtree(host)
    host.mkdir(parents=True)
    run([Path(src) / "configure", "--disable-tcl"], cwd=host, timeout=1800)
    run(["make", "sqlite3.c"], cwd=host, timeout=1800)
    for d in ("include", "lib/pkgconfig"):
        (PREFIX / d).mkdir(parents=True, exist_ok=True)
    for h in ("sqlite3.h", "sqlite3ext.h"):
        shutil.copy2(host / h if (host / h).exists() else Path(src) / "src" / h, PREFIX / "include" / h)
    obj = host / "sqlite3.o"
    run([*CC, "-O2", "-DSQLITE_ENABLE_FTS3", "-DSQLITE_ENABLE_FTS3_PARENTHESIS", "-DSQLITE_ENABLE_RTREE",
         "-DSQLITE_ENABLE_COLUMN_METADATA", "-DSQLITE_THREADSAFE=1", "-c", host / "sqlite3.c", "-o", obj], timeout=1800)
    (PREFIX / "lib" / "libsqlite3.a").unlink(missing_ok=True)
    run(["llvm-ar", "rcs", PREFIX / "lib" / "libsqlite3.a", obj])
    version = (Path(src) / "VERSION").read_text().strip()
    (PREFIX / "lib" / "pkgconfig" / "sqlite3.pc").write_text(
        f"prefix={PREFIX}\nlibdir=${{prefix}}/lib\nincludedir=${{prefix}}/include\n\nName: SQLite\n"
        f"Description: SQL database engine\nVersion: {version}\nLibs: -L${{libdir}} -lsqlite3\nCflags: -I${{includedir}}\n")


