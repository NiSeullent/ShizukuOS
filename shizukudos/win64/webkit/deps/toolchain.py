"""Provisional C/C++ toolchain for the WebKit dependencies and the Shizuku WebKit port (agent W3).

Agent W1 owns the WebKit toolchain. Until W1's toolchain exists on its branch, this script builds one so the W3
dependency work can start; it is recorded in docs/shizukudos10/reports/W3.md under "Needed from W1" and is meant to be
replaced by (or folded into) W1's.

What it is: the host's clang 18 / lld (Ubuntu packages, as used by win64/build.py for its MSVC-ABI C++ tests) targeting
x86_64-w64-mingw32, plus a sysroot built here from pinned sources:
  - mingw-w64 v13.0.0 headers and CRT, configured with --with-default-msvcrt=ucrt, so every image imports the C runtime
    through the api-ms-win-crt-* contracts that the Kernel64 loader maps to the Shizuku ucrtbase.dll (docs CRT.md);
  - compiler-rt builtins, libunwind, libc++abi and libc++ from llvm-project llvmorg-18.1.3 (the same LLVM release as the
    host clang), built for that target, both static and as DLLs (libc++.dll, libunwind.dll).
C++ exceptions use the Itanium ABI with SEH-based unwinding (libunwind's _GCC_specific_handler + ntdll RtlUnwindEx),
not vcruntime140's MSVC tables.

Output: build/shizukudos/webkit/toolchain/
  bin/x86_64-w64-mingw32-{clang,clang++}   wrapper scripts (target, sysroot, resource dir, runtimes, lld)
  x86_64-w64-mingw32/{include,lib,bin}     sysroot (mingw-w64 + libc++), bin/ holds libc++.dll, libunwind.dll
  resource/                                copy of the host clang resource dir plus the mingw builtins
  toolchain.cmake                          CMake toolchain file used by deps/build.py and the port
  toolchain.json                           pins, host tool versions, sha256 of the runtime DLLs
"""
import argparse
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[2] / "tools"))
import shzlib  # noqa: E402
from shzlib import BUILD, REPO, run  # noqa: E402

TRIPLE = "x86_64-w64-mingw32"
TC = BUILD / "webkit" / "toolchain"
SYSROOT = TC / TRIPLE
RESOURCE = TC / "resource"
WORK = REPO / "build" / "webkit-work" / "toolchain"
UPSTREAM = REPO / "build" / "upstream"
JOBS = str(os.cpu_count() or 2)
PATCHES = HERE / "patches"
SHZ_PARTS = 12                    # number of SHZ_PART sections in shim/shzucrt_fix.c
LLVM_TOOLS = {"ar": "llvm-ar", "ranlib": "llvm-ranlib", "nm": "llvm-nm", "dlltool": "llvm-dlltool",
              "objdump": "llvm-objdump"}


def fetch(name):
    """Shallow, optionally sparse, fetch of a manifest-pinned upstream into build/upstream/<name>; verifies the pin."""
    spec = shzlib.load_manifest()["upstreams"][name]
    dest = UPSTREAM / name
    head = lambda: subprocess.run(["git", "-C", str(dest), "rev-parse", "HEAD"], capture_output=True,  # noqa: E731
                                  text=True).stdout.strip()
    if (dest / ".git").exists() and head() == spec["commit"]:
        return dest
    if dest.exists():
        shutil.rmtree(dest)
    dest.mkdir(parents=True)
    run(["git", "-C", dest, "init", "-q"])
    run(["git", "-C", dest, "remote", "add", "origin", spec["repository"]])
    if spec.get("sparse_paths"):
        run(["git", "-C", dest, "sparse-checkout", "set", "--no-cone", *spec["sparse_paths"]])
    run(["git", "-C", dest, "fetch", "-q", "--depth", "1", "origin", spec["commit"]], timeout=3600)
    run(["git", "-C", dest, "checkout", "-q", "FETCH_HEAD"], timeout=1800)
    if head() != spec["commit"]:
        raise RuntimeError(f"{name}: pinned {spec['commit']} but found {head()}")
    return dest


def patched_source(name, work):
    """Pristine copy of the pinned tree (without .git) under `work`, with deps/patches/<name>/*.patch applied in order."""
    src = fetch(name)
    dest = work / f"src-{name}"
    if dest.exists():
        shutil.rmtree(dest)
    shutil.copytree(src, dest, symlinks=True, ignore=shutil.ignore_patterns(".git"))
    for patch in sorted((PATCHES / name).glob("*.patch")):
        run(["patch", "-p1", "-N", "--quiet", "-d", dest, "-i", patch])
    return dest


def host_clang_resource_dir():
    return Path(subprocess.run(["clang", "-print-resource-dir"], capture_output=True, text=True,
                               check=True).stdout.strip())


def cc_flags():
    return ["--target=" + TRIPLE, f"--sysroot={TC}", f"-resource-dir={RESOURCE}", "-rtlib=compiler-rt",
            "-unwindlib=libunwind", "-fuse-ld=lld"]


def write_wrappers():
    (TC / "bin").mkdir(parents=True, exist_ok=True)
    for name, drv, extra in (("clang", "clang", []), ("clang++", "clang++", ["-stdlib=libc++"])):
        p = TC / "bin" / f"{TRIPLE}-{name}"
        flags = " ".join(cc_flags() + extra)
        p.write_text(f"#!/bin/sh\n# generated by shizukudos/win64/webkit/deps/toolchain.py\nexec {drv} {flags} \"$@\"\n")
        p.chmod(0o755)
    for short, tool in LLVM_TOOLS.items():
        link = TC / "bin" / f"{TRIPLE}-{short}"
        if link.exists() or link.is_symlink():
            link.unlink()
        link.symlink_to(shutil.which(tool))
    (TC / "toolchain.cmake").write_text(f"""# generated by shizukudos/win64/webkit/deps/toolchain.py
set(CMAKE_SYSTEM_NAME Windows)
set(CMAKE_SYSTEM_PROCESSOR AMD64)
set(CMAKE_C_COMPILER {TC}/bin/{TRIPLE}-clang)
set(CMAKE_CXX_COMPILER {TC}/bin/{TRIPLE}-clang++)
set(CMAKE_ASM_COMPILER {TC}/bin/{TRIPLE}-clang)
set(CMAKE_RC_COMPILER {shutil.which('x86_64-w64-mingw32-windres') or 'x86_64-w64-mingw32-windres'})
set(CMAKE_AR {shutil.which('llvm-ar')})
set(CMAKE_RANLIB {shutil.which('llvm-ranlib')})
set(CMAKE_NM {shutil.which('llvm-nm')})
set(CMAKE_DLLTOOL {shutil.which('llvm-dlltool')})
list(APPEND CMAKE_FIND_ROOT_PATH {SYSROOT})
set(CMAKE_FIND_ROOT_PATH_MODE_PROGRAM NEVER)
set(CMAKE_FIND_ROOT_PATH_MODE_LIBRARY ONLY)
set(CMAKE_FIND_ROOT_PATH_MODE_INCLUDE ONLY)
set(CMAKE_FIND_ROOT_PATH_MODE_PACKAGE ONLY)
""")


def autotools(src, build, args, env):
    if build.exists():
        shutil.rmtree(build)
    build.mkdir(parents=True)
    run([src / "configure", *args], cwd=build, env=env, timeout=1800)
    run(["make", "-j" + JOBS], cwd=build, env=env, timeout=7200)
    run(["make", "install"], cwd=build, env=env, timeout=1800)


def cmake(src, build, defs, env=None):
    if build.exists():
        shutil.rmtree(build)
    run(["cmake", "-G", "Ninja", "-S", src, "-B", build, *[f"-D{k}={v}" for k, v in defs.items()]],
        env=env, timeout=1800)
    run(["ninja", "-C", build, "-j", JOBS], env=env, timeout=7200)
    run(["ninja", "-C", build, "install"], env=env, timeout=1800)


def build(clean=False):
    if clean and TC.exists():
        shutil.rmtree(TC)
    mingw = fetch("mingw-w64")
    llvm = patched_source("llvm-project-runtimes", WORK)
    TC.mkdir(parents=True, exist_ok=True)
    # 1. resource dir: host clang's headers; the mingw builtins are added in step 4.
    if RESOURCE.exists():
        shutil.rmtree(RESOURCE)
    shutil.copytree(host_clang_resource_dir(), RESOURCE, symlinks=False)
    write_wrappers()
    env = dict(os.environ)
    env["PATH"] = f"{TC / 'bin'}:{env['PATH']}"
    tools = {"CC": f"{TRIPLE}-clang", "CXX": f"{TRIPLE}-clang++", "AR": "llvm-ar", "RANLIB": "llvm-ranlib",
             "DLLTOOL": "llvm-dlltool", "NM": "llvm-nm"}
    env.update(tools)
    # 2. mingw-w64 headers (UCRT default, Windows 10 API level as WebKit's Win port expects).
    autotools(mingw / "mingw-w64-headers", WORK / "mingw-headers",
              [f"--host={TRIPLE}", f"--prefix={SYSROOT}", "--with-default-msvcrt=ucrt",
               "--with-default-win32-winnt=0xA00"], env)
    # 3. mingw-w64 CRT (import libraries for the api-ms-win-crt contracts, crt2.o/dllcrt2.o, libmingwex).
    autotools(mingw / "mingw-w64-crt", WORK / "mingw-crt",
              [f"--host={TRIPLE}", f"--prefix={SYSROOT}", f"--with-sysroot={TC}", "--with-default-msvcrt=ucrt",
               "--disable-lib32", "--enable-lib64", "--disable-dependency-tracking"], env)
    # 3b. The CRT shim (deps/shim/shzucrt_fix.c: names the Shizuku runtime DLLs do not export yet) and the import
    #     members it and the CRT need from outside the UCRT (ntdll!__C_specific_handler, bcryptprimitives!ProcessPrng,
    #     vcruntime140!__intrinsic_setjmp(ex)/longjmp, which Windows' ucrtbase also exports for the private contract)
    #     go into libmingwex.a, which the driver links before the UCRT import library.
    shim = WORK / "shim"
    if shim.exists():
        shutil.rmtree(shim)
    shim.mkdir(parents=True)
    for part in range(SHZ_PARTS):
        run([f"{TRIPLE}-clang", "-O2", "-Wall", "-Wno-inconsistent-dllimport", f"-DSHZ_PART={part}", "-c",
             HERE / "shim" / "shzucrt_fix.c", "-o", shim / f"shzucrt_fix{part}.o"], env=env)
    for dll, names in (("ntdll.dll", ["__C_specific_handler"]), ("bcryptprimitives.dll", ["ProcessPrng"]),
                       ("vcruntime140.dll", ["__intrinsic_setjmp", "__intrinsic_setjmpex", "longjmp"])):
        stem = dll.split(".")[0]
        (shim / f"{stem}.def").write_text(f"LIBRARY {dll}\nEXPORTS\n" + "".join(f"{n}\n" for n in names))
        run(["llvm-dlltool", "-m", "i386:x86-64", "-d", shim / f"{stem}.def", "-l", shim / f"libshz_{stem}.a"])
    mingwex = SYSROOT / "lib" / "libmingwex.a"
    run(["llvm-ar", "q", mingwex, *[shim / f"shzucrt_fix{part}.o" for part in range(SHZ_PARTS)]])
    for stem in ("ntdll", "bcryptprimitives", "vcruntime140"):
        run(["llvm-ar", "qL", mingwex, shim / f"libshz_{stem}.a"])
    run(["llvm-ranlib", mingwex])
    common = {"CMAKE_BUILD_TYPE": "Release", "CMAKE_SYSTEM_NAME": "Windows", "CMAKE_C_COMPILER": f"{TRIPLE}-clang",
              "CMAKE_CXX_COMPILER": f"{TRIPLE}-clang++", "CMAKE_ASM_COMPILER": f"{TRIPLE}-clang",
              "CMAKE_AR": shutil.which("llvm-ar"), "CMAKE_RANLIB": shutil.which("llvm-ranlib"),
              "CMAKE_C_COMPILER_WORKS": "1", "CMAKE_CXX_COMPILER_WORKS": "1", "CMAKE_C_COMPILER_TARGET": TRIPLE,
              "CMAKE_CXX_COMPILER_TARGET": TRIPLE, "CMAKE_ASM_COMPILER_TARGET": TRIPLE}
    # 4. compiler-rt builtins -> resource/lib/windows/libclang_rt.builtins-x86_64.a
    cmake(llvm / "compiler-rt/lib/builtins", WORK / "builtins", {
        **common, "CMAKE_INSTALL_PREFIX": RESOURCE, "COMPILER_RT_DEFAULT_TARGET_ONLY": "TRUE",
        "COMPILER_RT_USE_BUILTINS_LIBRARY": "TRUE", "COMPILER_RT_BUILD_BUILTINS": "TRUE",
        "COMPILER_RT_OS_DIR": "windows", "LLVM_CMAKE_DIR": llvm / "llvm/cmake/modules"}, env)
    # 5. libunwind + libc++abi + libc++ (shared and static), installed into the sysroot.
    cmake(llvm / "runtimes", WORK / "runtimes", {
        **common, "CMAKE_INSTALL_PREFIX": SYSROOT, "LLVM_ENABLE_RUNTIMES": "libunwind;libcxxabi;libcxx",
        "LIBUNWIND_USE_COMPILER_RT": "TRUE", "LIBUNWIND_ENABLE_SHARED": "TRUE", "LIBUNWIND_ENABLE_STATIC": "TRUE",
        "LIBCXX_USE_COMPILER_RT": "ON", "LIBCXX_ENABLE_SHARED": "ON", "LIBCXX_ENABLE_STATIC": "ON",
        "LIBCXX_ENABLE_STATIC_ABI_LIBRARY": "TRUE", "LIBCXX_CXX_ABI": "libcxxabi",
        "LIBCXX_LIBDIR_SUFFIX": "", "LIBCXX_INCLUDE_TESTS": "FALSE", "LIBCXX_INCLUDE_BENCHMARKS": "FALSE",
        "LIBCXX_ENABLE_ABI_LINKER_SCRIPT": "FALSE", "LIBCXX_HAS_WIN32_THREAD_API": "ON",
        "LIBCXX_ENABLE_NEW_DELETE_DEFINITIONS": "ON", "LIBCXXABI_ENABLE_NEW_DELETE_DEFINITIONS": "OFF",
        "LIBCXXABI_USE_COMPILER_RT": "ON", "LIBCXXABI_USE_LLVM_UNWINDER": "ON", "LIBCXXABI_ENABLE_SHARED": "OFF",
        "LIBCXXABI_LIBDIR_SUFFIX": "", "LIBCXXABI_HAS_WIN32_THREAD_API": "ON",
        "LIBCXX_ENABLE_LOCALIZATION": "ON", "LIBCXX_ENABLE_FILESYSTEM": "ON"}, env)
    info = {"triple": TRIPLE, "clang": shzlib.tool_version("clang"), "lld": shzlib.tool_version("ld.lld"),
            "upstreams": {n: shzlib.load_manifest()["upstreams"][n]["commit"]
                          for n in ("mingw-w64", "llvm-project-runtimes")},
            "runtime_dlls": {p.name: {"bytes": p.stat().st_size, "sha256": shzlib.sha256_file(p)}
                             for p in sorted((SYSROOT / "bin").glob("*.dll"))}}
    (TC / "toolchain.json").write_text(json.dumps(info, indent=1) + "\n")
    print(json.dumps(info, indent=1))


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--clean", action="store_true")
    build(ap.parse_args().clean)
