/* ---------------------------------------------------------------------------------------------------- node types */
enum {
    SHZ_ELEMENT_NODE = 1, SHZ_ATTRIBUTE_NODE = 2, SHZ_TEXT_NODE = 3, SHZ_CDATA_SECTION_NODE = 4,
    SHZ_PI_NODE = 7, SHZ_COMMENT_NODE = 8, SHZ_DOCUMENT_NODE = 9, SHZ_DOCTYPE_NODE = 10, SHZ_FRAGMENT_NODE = 11
};

/* namespaces */
enum { SHZ_NS_NONE = 0, SHZ_NS_HTML, SHZ_NS_SVG, SHZ_NS_MATHML, SHZ_NS_XML, SHZ_NS_XMLNS, SHZ_NS_XLINK, SHZ_NS_OTHER };

/* compareDocumentPosition bits */
#define SHZ_POS_DISCONNECTED  0x01
#define SHZ_POS_PRECEDING     0x02
#define SHZ_POS_FOLLOWING     0x04
#define SHZ_POS_CONTAINS      0x08
#define SHZ_POS_CONTAINED_BY  0x10
#define SHZ_POS_IMPL_SPECIFIC 0x20

/* node flags */
#define SHZ_NF_IN_DOC          0x0001   /* connected: a descendant of its document's Document node */
#define SHZ_NF_PARSER_INSERTED 0x0002   /* <script> created by the parser (not by parse_fragment) */
#define SHZ_NF_STARTED         0x0004   /* <script> "already started" (run_script was or will not be called) */
#define SHZ_NF_FREEING         0x0008   /* internal: being destroyed */
#define SHZ_NF_CREATED_BY_PARSER 0x0010 /* element created by the HTML parser (any kind) */

/* ---------------------------------------------------------------------------------------------------- nodes */
struct shzeng_node {
    uint32_t refs;
    uint16_t type;                      /* SHZ_*_NODE */
    uint16_t flags;                     /* SHZ_NF_* */
    shz_doc *doc;                       /* owner document (for the Document node: its own document) */
    shz_node *parent, *first_child, *last_child, *prev_sibling, *next_sibling;
    void *host_data;                    /* engine.h node_set_host_data (not reference counted) */
    struct shz_box *box;                /* L1 (layout.h): layout object(s) generated by this node */
    struct shz_listener *listeners;     /* L2 (events.h): event listeners registered on this node */
};

typedef struct shz_attr {
    shz_char *name;                     /* qualified name; lower-case on HTML elements of HTML documents */
    shz_char *value;                    /* never NULL */
    uint32_t value_len;
    uint16_t id;                        /* SHZ_ATTR_* (known HTML attribute name), 0 otherwise */
    uint16_t ns;                        /* SHZ_NS_* of the attribute (SHZ_NS_NONE normally) */
    shz_node *node;                     /* the Attr node handed out for this attribute (weak) */
} shz_attr;

typedef struct shz_element {
    shz_node node;
    uint16_t tag;                       /* SHZ_TAG_* (names.h) */
    uint8_t ns;                         /* SHZ_NS_* */
    uint8_t eflags;                     /* reserved */
    shz_char *qname;                    /* qualified name (lower-case for HTML elements in HTML documents) */
    const shz_char *local;              /* local name: qname after the prefix */
    uint32_t qname_len;
    shz_char *ns_uri;                   /* namespace URI when ns == SHZ_NS_OTHER, else NULL */
    shz_attr *attrs;
    uint32_t attr_count, attr_cap;
    /* module data, created lazily and freed by the owning module on SHZ_CHG_DESTROYED */
    struct shz_style_elem *style;       /* L1 (style.h): inline declaration block, computed style cache */
    struct shz_ctl *ctl;                /* L2 (forms.h): form control state (value, checkedness, selection) */
    struct shz_img *img;                /* L2 (image.h): <img>/<input type=image> image state */
} shz_element;

/* text, comment, CDATA section, processing instruction */
typedef struct shz_chardata {
    shz_node node;
    shz_char *data;                     /* NUL-terminated */
    uint32_t len, cap;
    shz_char *target;                   /* processing instructions only */
} shz_chardata;

typedef struct shz_doctype {
    shz_node node;
    shz_char *name, *public_id, *system_id;   /* public_id / system_id NULL when missing */
} shz_doctype;

/* Attr node (elem_attr_node). While owner != NULL it reflects owner's attribute `name` and holds a reference on the
 * owner; when that attribute is removed it keeps a copy of the last value. */
typedef struct shz_attrnode {
    shz_node node;
    shz_node *owner;
    shz_char *name;
    shz_char *value;                    /* only while detached */
} shz_attrnode;

static inline shz_element *shz_elem(shz_node *n)
{
    return n && n->type == SHZ_ELEMENT_NODE ? (shz_element *)n : NULL;
}
/* HTML element with the given SHZ_TAG_* id? */
static inline int shz_is_tag(const shz_node *n, int tag)
{
    return n && n->type == SHZ_ELEMENT_NODE && ((const shz_element *)n)->tag == tag
           && ((const shz_element *)n)->ns == SHZ_NS_HTML;
}
static inline int shz_tag_of(const shz_node *n)
{
    return n && n->type == SHZ_ELEMENT_NODE && ((const shz_element *)n)->ns == SHZ_NS_HTML ? ((const shz_element *)n)->tag : 0;
}
static inline int shz_is_chardata(const shz_node *n)
{
    return n && (n->type == SHZ_TEXT_NODE || n->type == SHZ_COMMENT_NODE || n->type == SHZ_CDATA_SECTION_NODE
                 || n->type == SHZ_PI_NODE);
}
static inline shz_chardata *shz_cdata(shz_node *n)
{
    return shz_is_chardata(n) ? (shz_chardata *)n : NULL;
}
static inline int shz_is_text(const shz_node *n)
{
    return n && (n->type == SHZ_TEXT_NODE || n->type == SHZ_CDATA_SECTION_NODE);
}
static inline int shz_in_doc(const shz_node *n) { return n && (n->flags & SHZ_NF_IN_DOC); }

