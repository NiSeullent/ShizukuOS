/* Host callbacks in core types (the glue adapts engine.h's shzeng_host to this; the host tests implement it). Every
 * member may be NULL. They mirror shzeng_host exactly (see engine.h for the semantics). */
typedef struct shz_doc_hooks {
    void    (*node_inserted)(void *ctx, shz_doc *doc, shz_node *node);
    void    (*node_removed)(void *ctx, shz_doc *doc, shz_node *node);
    void    (*parse_done)(void *ctx, shz_doc *doc);
    void    (*run_script)(void *ctx, shz_doc *doc, shz_node *script, int parser_inserted);
    shz_res (*event)(void *ctx, shz_node *current_target, shz_event *ev, void *cookie);   /* SHZ_FALSE: preventDefault */
    shz_res (*fetch)(void *ctx, shz_doc *doc, const shz_char *url, int kind, shz_fetch_sink *sink);
    void    (*load_done)(void *ctx, shz_doc *doc);
    void    (*title_changed)(void *ctx, shz_doc *doc);
    void    (*status_text)(void *ctx, const shz_char *text);
    shz_res (*navigate)(void *ctx, shz_doc *doc, const shz_char *url, const shz_char *target, const void *post,
                        size_t post_len, const shz_char *headers);
    void    (*context_menu)(void *ctx, shz_doc *doc, int32_t screen_x, int32_t screen_y, shz_node *node);
    void    (*invalidate)(void *ctx, shz_doc *doc, const shz_irect *rect);
} shz_doc_hooks;

/* document modes: the values of engine.h shzeng_mode */
enum { SHZ_MODE_QUIRKS = 0, SHZ_MODE_IE5, SHZ_MODE_IE7, SHZ_MODE_IE8, SHZ_MODE_IE9, SHZ_MODE_IE10, SHZ_MODE_IE11 };
/* rendering modes (HTML "quirks mode" / "limited-quirks mode" / "no-quirks mode") */
enum { SHZ_QUIRKS_NONE = 0, SHZ_QUIRKS_LIMITED = 1, SHZ_QUIRKS_FULL = 2 };
/* document.readyState */
enum { SHZ_READY_UNINITIALIZED = 0, SHZ_READY_LOADING, SHZ_READY_INTERACTIVE, SHZ_READY_COMPLETE };

struct shzeng_doc {
    uint32_t refs;                      /* document handles + internal holders that keep it open (fetch sinks, views) */
    uint32_t pinned;                    /* nodes of this document with refs > 0 */
    uint8_t closed;                     /* refs reached 0: parser and module state torn down */
    uint8_t freeing;
    uint8_t is_html;                    /* HTML document (else XML: case-sensitive names, no HTML parser rules) */
    uint8_t scripting;                  /* HTML "scripting flag" (<noscript> is raw text); always 1 here */
    shz_node *node;                     /* the Document node */
    shz_char *url;                      /* document URL ("about:blank" by default) */
    shz_char *content_type;             /* "text/html", "application/xml", ... */
    shz_char *charset;                  /* the encoding the parser used ("UTF-8", "windows-1252", "UTF-16LE"...) */
    uint64_t version;                   /* bumped by every tree or attribute mutation (validates live-list caches) */

    /* modes: doc_set_mode stores the Trident mode; until it is called the doctype decides (HTML5 rules) */
    int mode;                           /* SHZ_MODE_* */
    uint8_t mode_set;                   /* doc_set_mode was called */
    uint8_t doctype_quirks;             /* SHZ_QUIRKS_* from the doctype the parser saw */

    const shz_doc_hooks *hooks;
    void *hooks_ctx;
    void *platform;                     /* the Windows glue's per-document data (engine.h host + ctx) */
    void (*platform_free)(void *platform);  /* called when the document is freed */

    shz_parser *parser;                 /* active HTML parser, or NULL */
    int ready_state;                    /* SHZ_READY_*; written by the loader (loader.h, L2) and the parser */
    uint32_t fetch_pending;             /* sub-resource fetches in flight that delay "load" (fetch.c) */
    shz_range *selection;               /* the document selection (sel_get/sel_set), reference held */
    shz_range *live_ranges;             /* every range of this document (range.c keeps boundaries valid) */

    /* interaction state: written by L2 (events/view/forms), read by selectors (:hover/:focus/:active) and L1 paint.
     * References are held; L2 clears them when the node leaves the document (SHZ_CHG_REMOVED) and on close. */
    shz_node *focus;                    /* focused element (NULL = the document/body) */
    shz_node *hover;                    /* innermost element under the mouse */
    shz_node *active;                   /* element being activated (mouse button down) */

    /* viewport: written by the view (L2) / snapshot / view_paint (L1), read by layout */
    int32_t viewport_w, viewport_h;     /* initial containing block size in CSS px */
    int32_t scroll_x, scroll_y;         /* viewport scroll position */
    float zoom;                         /* 1.0 */

    /* module state, owned by the named module and released on SHZ_CHG_DOC_CLOSED */
    struct shz_css_doc *css;            /* L1: style sheets, cascade caches */
    struct shz_layout_doc *layout;      /* L1: box tree, display list */
    struct shz_events_doc *events;      /* L2: window listeners, pending events */
    struct shz_forms_doc *forms;        /* L2 */
    struct shz_images_doc *images;      /* L2: image cache */
    struct shz_load_doc *load;          /* L2: readyState / DOMContentLoaded / load bookkeeping */
    struct shz_view_list *views;        /* L2 (win): views presenting this document */
};

