static int cmp(const shz_char *s, size_t n, const char *name)
{
    size_t i;
    for (i = 0; i < n; ++i) {
        unsigned char c = (unsigned char)name[i];
        if (!c) return 1;
        if (s[i] != c) return s[i] < c ? -1 : 1;
    }
    return name[n] ? -1 : 0;
}

static int find(const shz_char *s, size_t n)
{
    int lo = 0, hi = (int)SHZ_ARRAY_SIZE(entities) - 1;
    while (lo <= hi) {
        int mid = (lo + hi) / 2, c = cmp(s, n, entities[mid].name);
        if (!c) return mid;
        if (c < 0) hi = mid - 1;
        else lo = mid + 1;
    }
    return -1;
}

size_t shz_entity_match(const shz_char *s, size_t n, uint32_t *cp, int *semicolon)
{
    size_t len = n < SHZ_ENTITY_MAX_LEN ? n : SHZ_ENTITY_MAX_LEN;
    for (; len > 0; --len) {
        int i = find(s, len);
        if (i >= 0) {
            *cp = entities[i].cp;
            *semicolon = s[len - 1] == ';';
            return len;
        }
    }
    return 0;
}
